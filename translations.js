// ფუნქცია, რომელიც ავტომატურად ცვლის ტექსტებს ნებისმიერ გვერდზე
export function applyTranslations() {
  const currentLang = localStorage.getItem("gabji_language") || "ka";
  const dict = translations[currentLang] || translations["ka"];

  // 1. ჩვეულებრივი ტექსტების თარგმნა
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict && dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // 2. Placeholder ინპუტების თარგმნა
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("data-i18n-ph");
    if (dict && dict[key]) {
      el.placeholder = dict[key];
    }
  });
}
